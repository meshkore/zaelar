"""Spoken words carry the trace of the turn that MADE them (V2-831 T-23).

Demo pass 7: M3's NASDAQ reply was generated by turn T66, but its `transcript · zaelar` event — emitted by
LiveKit's `conversation_item_added` when the PLAYOUT ends — landed while M4 (T67) was live, and was stamped
`T67` because the emitter read `trace.active()`. The Master attributed M3's answer to M4.

Class: every event that describes a speech's output (the spoken transcript, its TTS metric) carries the trace
bound to that speech when its turn decided its trace (`flow_lifecycle._begin_or_adopt_trace`, inside the speech's
own generation task), never the «current» trace at the end.

Disarm: `trace.of_speech` returns "" → the emitters fall back to `active()` → red.
"""
from __future__ import annotations

import asyncio
import contextvars
from types import SimpleNamespace

from livekit.agents.voice.agent_activity import _SpeechHandleContextVar

from voice import trace
from voice.engine.llm.providers.nucleo import NucleoLLM, _begin_or_adopt_trace


def _turn_in_speech(speech_id: str, text: str) -> tuple[str, contextvars.Context]:
    """A turn's generation running inside its LiveKit speech task: returns its trace and the task's context."""
    ctx = contextvars.copy_context()

    def run():
        _SpeechHandleContextVar.set(SimpleNamespace(id=speech_id))
        _begin_or_adopt_trace(NucleoLLM(), text, False)
        return trace.current()
    return ctx.run(run), ctx


def test_a_reply_whose_playout_ends_in_the_next_turn_keeps_its_own_trace(monkeypatch):
    from voice.engine.pipeline import agent as _ag, agent_events
    monkeypatch.setattr(_ag._reply_wall, "already_surfaced", lambda t: False)
    tid_a, ctx_a = _turn_in_speech("SPEECH_A", "and the nasdaq, over the whole year")
    tid_b, _ = _turn_in_speech("SPEECH_B", "ok close that")       # turn B is now the live one
    assert tid_a and tid_b and tid_a != tid_b and trace.active() == tid_b
    emitted = []
    item = SimpleNamespace(role="assistant", text_content="The NASDAQ Composite is at 26,549.85")
    # A's playout ends now, inside A's speech task (where LiveKit adds the item), during turn B
    ctx_a.run(agent_events._on_item, SimpleNamespace(item=item),
              _emit=lambda kind, label, **kw: emitted.append((kind, (kw.get("extra") or {}).get("trace"))))
    assert ("transcript", tid_a) in emitted, f"A's words were stamped {emitted}, A is {tid_a}, B is {tid_b}"
    trace.adopt("")


def test_the_tts_metric_of_a_speech_names_the_turn_that_made_it(monkeypatch):
    from voice.engine.pipeline import metrics_tap
    monkeypatch.setattr(metrics_tap, "SETTINGS", SimpleNamespace(tts_provider="inworld", stt_provider="deepgram"))
    from nucleo.energy import meter
    monkeypatch.setattr(meter, "report_tts_usage", lambda **k: None)
    tid_a, _ = _turn_in_speech("SPEECH_C", "how is the s&p doing")
    _turn_in_speech("SPEECH_D", "ok close that")
    m = type("TTSMetrics", (), {"duration": 1.2, "speech_id": "SPEECH_C", "characters_count": 40})()
    emitted = []
    metrics_tap.on_metrics(SimpleNamespace(metrics=m),
                           lambda kind, label, **kw: emitted.append((kind, (kw.get("extra") or {}).get("trace"))))
    assert ("tts", tid_a) in emitted, f"the TTS metric was stamped {emitted}, its speech's turn is {tid_a}"
    trace.adopt("")


def test_an_unbound_speech_still_falls_back_to_the_live_turn():
    """A `say()` or a filler has no turn of its own: the reader keeps the old behaviour for it."""
    assert trace.of_speech("NEVER_BOUND") == ""
