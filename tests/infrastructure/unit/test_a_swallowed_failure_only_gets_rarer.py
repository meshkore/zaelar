"""A failure swallowed in silence only gets RARER (V2-778 F2-20, 2026-10-01).

The audit counted the `except …: pass` handlers in product code — a failure that exits EMPTY, the class this house
names as the worst, because nothing distinguishes «it failed» from «there was nothing to do». They had grown by
217 in the demo week alone. This ratchet freezes today's count per file: a file may not gain a swallow-only
handler, and the total may only fall. The fix for one is a `_note`/`emit` that says what failed, not a comment.

Counted by AST over tracked product files (tests excluded): an `except` whose whole body is `pass` (or `...`),
or — since 2026-10-16 (audit V2-783 P1-4: 23 broad handlers of the window exited as `return False/None/{}` and this
ratchet could not see one of them) — a bare `return` of a falsy constant or an empty container, or `continue`. The
baseline below was re-measured with that predicate the same day; it may only fall from there.
"""
from __future__ import annotations

import ast
import subprocess
from pathlib import Path

ENGINE = Path(__file__).resolve().parents[3]


def _silent(b) -> bool:
    """A statement that leaves a failure indistinguishable from «nothing to do»."""
    if isinstance(b, (ast.Pass, ast.Continue)):
        return True
    if isinstance(b, ast.Expr) and isinstance(b.value, ast.Constant) and b.value.value is Ellipsis:
        return True
    if isinstance(b, ast.Return):
        v = b.value
        if v is None or (isinstance(v, ast.Constant) and not v.value):
            return True
        if isinstance(v, (ast.Dict, ast.List, ast.Tuple, ast.Set)) and not getattr(v, "elts", getattr(v, "keys", None)):
            return True
    return False


def _counts() -> dict[str, int]:
    out = subprocess.run(["git", "ls-files", "*.py"], cwd=ENGINE, capture_output=True, text=True).stdout.split()
    counts: dict[str, int] = {}
    for rel in out:
        if rel.startswith("tests/") or "/tests/" in rel:
            continue
        p = ENGINE / rel
        if not p.exists():
            continue
        try:
            tree = ast.parse(p.read_text(encoding="utf-8"))
        except (SyntaxError, UnicodeDecodeError):
            continue
        n = 0
        for node in ast.walk(tree):
            if isinstance(node, ast.ExceptHandler) and all(_silent(b) for b in node.body):
                n += 1
        if n:
            counts[rel] = n
    return counts


