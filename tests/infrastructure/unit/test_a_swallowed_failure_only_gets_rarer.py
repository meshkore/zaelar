"""A failure swallowed in silence only gets RARER (V2-778 F2-20, 2026-10-01).

The audit counted the `except …: pass` handlers in product code — a failure that exits EMPTY, the class this house
names as the worst, because nothing distinguishes «it failed» from «there was nothing to do». They had grown by
217 in the demo week alone. This ratchet freezes today's count per file: a file may not gain a swallow-only
handler, and the total may only fall. The fix for one is a `_note`/`emit` that says what failed, not a comment.

Counted by AST over tracked product files (tests excluded): an `except` whose whole body is `pass` (or `...`).
"""
from __future__ import annotations

import ast
import subprocess
from pathlib import Path

ENGINE = Path(__file__).resolve().parents[3]


def _counts() -> dict[str, int]:
    out = subprocess.run(["git", "ls-files", "*.py"], cwd=ENGINE, capture_output=True, text=True).stdout.split()
    counts: dict[str, int] = {}
    for rel in out:
        if rel.startswith("tests/") or "/tests/" in rel:
            continue
        p = ENGINE / rel
        if not p.exists():
            continue
        try:
            tree = ast.parse(p.read_text(encoding="utf-8"))
        except (SyntaxError, UnicodeDecodeError):
            continue
        n = 0
        for node in ast.walk(tree):
            if isinstance(node, ast.ExceptHandler) and all(
                    isinstance(b, ast.Pass) or (isinstance(b, ast.Expr) and isinstance(b.value, ast.Constant)
                                                and b.value.value is Ellipsis) for b in node.body):
                n += 1
        if n:
            counts[rel] = n
    return counts


