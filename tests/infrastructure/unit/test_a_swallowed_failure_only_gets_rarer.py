def test_no_file_gains_a_swallowed_failure():
    now = _counts()
    grown = sorted(f"{f}: {n} (was {PER_FILE.get(f, 0)})" for f, n in now.items() if n > PER_FILE.get(f, 0))
    assert not grown, ("a failure is swallowed in silence where it was not before — say what failed (`_note` / "
                       f"`emit`) instead: {grown[:12]}")


